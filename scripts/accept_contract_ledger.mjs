import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';

const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const [origin,fixturePath]=process.argv.slice(2);
assert(/^http:\/\/127\.0\.0\.1:\d+$/.test(origin));
const root=path.resolve(fixturePath);
assert(root.startsWith(path.resolve('qa')+path.sep));
const fixture=JSON.parse(await fs.readFile(path.join(root,'fixture.json'),'utf8'));
assert(fixture.synthetic && fixture.url===origin);
const output=path.join(root,'browser');
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({...(process.env.WORKBENCH_BROWSER ? {executablePath:process.env.WORKBENCH_BROWSER} : {}),headless:true,args:['--disable-background-networking','--no-first-run']});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const errors=[],checks=[];
page.on('pageerror',error=>errors.push(error.message));
const check=label=>checks.push({label,status:'passed'});
const idle=()=>page.waitForFunction(()=>typeof state!=='undefined' && main.getAttribute('aria-busy')==='false' && !editorSubmitting);
const close=async()=>{await page.locator('#editor-cancel').click();await page.waitForFunction(()=>!editor.open);};
const overview=()=>page.evaluate(()=>api('contract_ledger'));
try {
  await page.goto(origin+'/#contracts');
  await idle();
  assert.equal(await page.evaluate(()=>state.boot.demo),true);
  let data=await overview();
  assert.equal(data.customer_count,47);
  assert.equal(await page.locator('#contract-customers tbody tr').count(),40);
  await page.screenshot({path:path.join(output,'customers-desktop.png'),fullPage:false});
  check('customer overview, pagination and lifetime summary');

  await page.locator('#next-page').click();await idle();
  await page.evaluate(()=>window.scrollTo(0,350));
  const parentTop=await page.evaluate(()=>scrollY);
  const selected=await page.locator('.contract-name-link[data-customer]').first().getAttribute('data-customer');
  await page.locator('.contract-name-link[data-customer]').first().click();await idle();
  await page.locator('#contract-customers-back').waitFor();
  await page.locator('#contract-customers-back').click();await idle();
  await page.locator('#contract-customers').waitFor();
  await page.waitForFunction(()=>state.page===1);
  assert(Math.abs((await page.evaluate(()=>scrollY))-parentTop)<10);
  check('customer back restores overview page and scroll position');

  await page.locator('#contract-business-scope').selectOption('contracts');await idle();
  await page.locator('#contract-year').selectOption('2025');await idle();
  assert.equal(await page.locator('#contract-customers tbody tr').count(),1);
  await page.locator('.contract-name-link[data-customer="customer:1"]').click();await idle();
  await page.locator('#records tbody tr').waitFor();
  assert.equal(await page.locator('#records tbody tr').count(),1);
  assert.match(await page.locator('#records').innerText(),/按实际结算/);
  assert.match(await page.locator('.contract-summary').innerText(),/17,000\.03/);
  assert.match(await page.locator('.contract-summary').innerText(),/1,200\.02/);
  check('signing-year filter includes later-year income and receipts');
  await page.screenshot({path:path.join(output,'contracts-desktop.png'),fullPage:false});

  await page.locator(`[data-contract-detail="${fixture.contract}"][data-kind="receipts"]`).click();
  await page.waitForFunction(()=>editor.open && !!document.querySelector('#contract-facts'));
  assert.match(await page.locator('#contract-facts').innerText(),/1,200\.02/);
  await page.locator('[data-contract-fact]').first().click();
  await page.locator('#record-detail-back').click();
  await page.waitForSelector('#contract-facts');
  await page.locator('[data-contract-tab="overview"]').click();
  assert.match(await page.locator('#contract-projects').innerText(),/据实关联/);
  await page.locator('#contract-dialog-files').click();
  await page.waitForSelector('#attachment-context-back');
  assert.match(await page.locator('#editor-body').innerText(),/合成合同预览.pdf/);
  await page.locator('[data-attachment-preview]').first().click();
  await page.waitForFunction(()=>document.querySelector('#attachment-preview').open);
  await page.locator('#attachment-preview-done').click();
  await page.locator('#attachment-context-back').click();
  await page.waitForSelector('#contract-dialog-files');
  await page.locator('#contract-dialog-allocation').click();
  await page.waitForFunction(()=>editor.open && !!form.elements.namedItem('contract_id'));
  assert.equal(await page.locator('[name="contract_id"]').inputValue(),String(fixture.contract));
  await close();
  await page.locator(`[data-contract-detail="${fixture.contract}"][data-kind="receipts"]`).click();
  await page.waitForSelector('#contract-dialog-settlement');
  await page.locator('#contract-dialog-settlement').click();
  await page.waitForFunction(()=>editor.open && !!form.elements.namedItem('contract_id') && editorLookups.size===0);
  assert.equal(await page.locator('[name="contract_id"]').inputValue(),String(fixture.contract));
  assert.equal(await page.locator('[name="project_id"]').inputValue(),String(fixture.project));
  check('amount drill-down, original record back, allocations and attachment preview');
  await close();

  await page.locator(`[data-contract-files="${fixture.contract}"]`).click();
  await page.locator('input[name="attachment"]').setInputFiles(fixture.pdf);
  await page.locator('#editor-save').click();
  await page.waitForFunction(()=>!editorSubmitting && document.querySelectorAll('#editor-body .list-note').length===2);
  await close();
  assert.match(await page.locator(`[data-contract-files="${fixture.contract}"]`).innerText(),/2 个附件/);
  check('attachment upload immediately refreshes contract list count');

  await page.locator('#contract-new').click();
  await page.waitForFunction(()=>editor.open && !!form.elements.namedItem('customer_partner_id'));
  assert.equal(await page.locator('[name="customer_partner_id"]').inputValue(),'1');
  await close();
  assert.equal((await overview()).contract_count,data.contract_count);
  check('new contract inherits selected customer; cancel creates no record');

  await page.locator('#contract-year').selectOption('');await idle();
  assert.equal(await page.locator('#records tbody tr').count(),2);
  await page.locator('#record-search').fill('跨年据实');
  await page.locator('#search-records').click();await idle();
  assert.equal(await page.locator('#records tbody tr').count(),1);
  await page.locator('#contract-status').selectOption('completed');await idle();
  assert.match(await page.locator('#main').innerText(),/当前范围没有业务记录/);
  await page.locator('#contract-clear').click();await idle();
  await page.locator('#contract-business-scope').selectOption('contracts');await idle();
  await page.locator('#contract-entity').selectOption('2');await idle();
  assert.equal(await page.locator('#records tbody tr').count(),1);
  check('search, empty state, status, clear and entity filters');

  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(100);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
  await page.screenshot({path:path.join(output,'contracts-mobile.png'),fullPage:true});
  await page.locator(`.contract-name-link[data-contract-detail="${fixture.contract}"][data-kind="overview"]`).click();
  await page.waitForSelector('#contract-dialog-files');
  assert(await page.locator('#editor-cancel').isVisible());
  await page.screenshot({path:path.join(output,'detail-mobile.png'),fullPage:false});
  await close();
  check('mobile layout has no page overflow and dialog actions remain reachable');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#contract-clear').click();await idle();
  await page.goto(origin+'/#contracts?view=all');await idle();
  await page.locator('#records tbody tr').first().waitFor();
  assert.equal(await page.locator('#records tbody tr').count(),40);
  await page.locator('[data-tab="allocations"]').click();await idle();
  await page.locator('[data-tab="allocations"][aria-selected="true"]').waitFor();
  assert.match(await page.locator('#records').innerText(),/DEMO-HT-001/);
  await page.locator('[data-tab="contracts"]').click();await idle();
  await page.locator('#contract-business-scope').waitFor();
  await page.locator('#project-scope').selectOption(String(fixture.project),{force:true});await idle();
  assert.equal(await page.locator('#records tbody tr').count(),2);
  assert.match(await page.locator('.contract-list-caption').innerText(),/当前项目累计/);
  check('all contracts, existing bulk tabs and project scope still work');
  assert.deepEqual(errors,[]);
} finally {
  await fs.writeFile(path.join(output,'result.json'),JSON.stringify({checks,errors},null,2));
  await browser.close();
}
console.log(JSON.stringify({checks,errors},null,2));
