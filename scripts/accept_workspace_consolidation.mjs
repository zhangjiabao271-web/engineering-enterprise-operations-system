// Real browser checks against a fresh synthetic fixture only.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const [origin,fixturePath]=process.argv.slice(2);
assert(/^http:\/\/127\.0\.0\.1:\d+$/.test(origin));
const root=path.resolve(fixturePath);
assert(root.startsWith(path.resolve('qa')+path.sep));
const fixture=JSON.parse(await fs.readFile(path.join(root,'fixture.json'),'utf8'));
assert(fixture.synthetic && fixture.url===origin);
const output=path.join(root,'browser');
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({...(process.env.WORKBENCH_BROWSER ? {executablePath:process.env.WORKBENCH_BROWSER} : {}),headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const errors=[],checks=[];
page.on('pageerror',error=>errors.push(error.message));
const idle=()=>page.waitForFunction(()=>{
  if(typeof state==='undefined' || main.getAttribute('aria-busy')!=='false')return false;
  const [route,search='']=location.hash.slice(1).split('?');
  const tab=new URLSearchParams(search).get('tab');
  return state.route===route && (!tab || state.collection===tab);
});
const go=async hash=>{await page.goto(origin+'/'+hash);await idle();};
const close=async()=>{await page.locator('#editor-cancel').click();await page.waitForFunction(()=>!editor.open);};
const check=label=>checks.push({label,status:'passed'});
try {
  await go('#projects');
  assert.equal(await page.locator('.nav-link').count(),16);
  for (const route of ['profit','compare','cashflow']) assert.equal(await page.locator(`.nav-link[data-route="${route}"]`).count(),0);
  assert.equal(await page.locator('[data-tab="profit"]').count(),1);
  const before=await page.evaluate(()=>api('qa_state'));
  check('一级导航收拢至16项，保留独立业务事实和项目核算页签');
  await go('#home');
  await page.locator('.cockpit-projects summary').click();
  const cockpitPending=page.locator('#cockpit-project-records tbody tr').filter({hasText:'尚未确认收入'});
  assert.match(await cockpitPending.innerText(),/-¥111\.01/);
  assert.match(await page.locator('#cockpit-project-records thead').innerText(),/账面毛利/);
  await go('#profit');
  assert.match(page.url(),/#projects\?tab=profit$/);
  const profit=await page.evaluate(()=>api('dashboard?view=profit'));
  const total=profit.accounting_summary;
  assert.equal(BigInt(total.gross_profit_minor),BigInt(total.confirmed_gross_profit_minor)+BigInt(total.pending_gross_profit_minor));
  assert.match(await page.locator('.metrics').innerText(),/账面毛利/);
  const pending=page.locator('#project-accounting tbody tr').filter({hasText:'尚未确认收入'});
  assert.match(await pending.innerText(),/-¥111\.01/);
  assert.match(await pending.innerText(),/待补合同及确认收入/);
  await pending.locator('[data-ledger-kind="profit"]').click();
  await page.locator('#ledger-close').waitFor();
  assert.match(await page.locator('#editor-body').innerText(),/暂不计入已确认毛利/);
  await close();
  await page.screenshot({path:path.join(output,'project-accounting.png'),fullPage:false});
  check('账面/已确认/待完善毛利守恒，成本未隐藏，点击沿用原明细');
  await go('#cost');
  assert.equal(await page.locator('#cost-ledger-create').innerText(),'登记其他费用');
  await page.locator('#cost-ledger-create').click();
  await page.locator('#editor-save').waitFor();
  await close();
  check('成本入口明确只登记其他费用，取消不写账');
  await go('#compare');
  assert.match(page.url(),/#offers\?tab=compare$/);
  await page.locator('[data-tab="offers"]').click();await idle();
  await page.locator('#new-record').waitFor();
  assert.match(await page.locator('h1').innerText(),/材料/);
  await go('#cashflow');
  assert.match(page.url(),/#funds\?tab=cashflow$/);
  await page.locator('[data-tab="accounts"]').click();await idle();
  assert.equal(await page.locator('#records tbody tr').count(),1);
  check('旧比价/分析链接兼容，内页签可切换回原台账');
  await go('#governance');
  assert.equal(await page.locator('[data-operation="entity_assign"]').count(),0);
  assert.equal(await page.locator('#read-business').count(),0);
  await go('#tools');
  assert.equal(await page.locator('#read-business').isVisible(),false);
  check('主体确认不再多处重复，内部编号控制台默认折叠');
  await go('#customers');
  await page.locator('#partner-records').waitFor();
  await page.locator('#partner-records .operation-menu summary').first().click();
  await page.locator('[data-operation="customer_deactivate"]').first().click();
  await page.locator('#editor-save').waitFor();await close();
  await page.locator('#partner-year').selectOption('2026');await idle();
  const customerData=await page.evaluate(()=>api('dashboard?view=customers&year=2026'));
  assert.equal(BigInt(customerData.summary.yearly_business_minor),10100000n);
  assert.equal(BigInt(customerData.summary.yearly_receipt_minor),2000000n);
  assert.equal(await page.locator('#partner-records tbody tr').count(),2);
  await page.screenshot({path:path.join(output,'customers-desktop.png'),fullPage:false});
  await page.locator('#partner-search').fill('零星');
  await page.locator('#partner-filters button[type="submit"]').click();await idle();
  assert.equal(await page.locator('#partner-records tbody tr').count(),1);
  await page.locator('#partner-records a').filter({hasText:'项目业务'}).click();await idle();
  assert.match(page.url(),new RegExp('customer='+fixture.customer));
  assert.equal(await page.locator('#records tbody tr').count(),2);
  await page.locator('[data-tab="profit"]').click();await idle();
  assert.equal(await page.locator('#project-accounting tbody tr').count(),2);
  await page.locator('#navigation-back').click();await idle();
  await page.waitForURL(new RegExp('#projects\\?customer='+fixture.customer+'$'));
  await page.locator('#navigation-back').click();await idle();
  await page.waitForURL('**/#customers');
  assert.equal(await page.locator('#partner-search').inputValue(),'零星');
  assert.equal(await page.locator('#partner-records tbody tr').count(),1);
  check('客户包含无合同现金工程，项目/核算按客户精确过滤，返回恢复搜索');
  await go('#contracts');
  await page.locator('#contract-business-scope').selectOption('contracts');await idle();
  await page.locator('#contract-year').selectOption('2025');await idle();
  assert.match(await page.locator('.contract-summary').innerText(),/100,000\.00/);
  check('客户收入按确认年度，合同仍按签约年选取后看全周期');
  await go('#suppliers');
  await page.locator('[data-partner-kind="distributor"]').click();await idle();
  assert.equal(await page.locator('#partner-records tbody tr').count(),1);
  await page.locator('#partner-records .operation-menu summary').click();
  await page.locator('[data-operation="supplier_deactivate"]').click();
  await page.locator('#editor-save').waitFor();await close();
  assert.match(await page.locator('#partner-records tbody').innerText(),/200\.00/);
  await page.screenshot({path:path.join(output,'suppliers-desktop.png'),fullPage:false});
  await page.locator('#partner-records .table-actions a').filter({hasText:'报价',exact:true}).click();await idle();
  assert.equal(await page.locator('#records tbody tr').count(),1);
  assert.match(await page.locator('#records').innerText(),/焊条/);
  await page.locator('#navigation-back').click();await idle();
  assert.equal(await page.locator('[data-partner-kind="distributor"]').getAttribute('aria-pressed'),'true');
  await page.locator('#partner-records .table-actions a').filter({hasText:'采购',exact:true}).click();await idle();
  assert.equal(await page.locator('#records tbody tr').count(),1);
  assert.match(await page.locator('#records').innerText(),/焊条/);
  check('供应商分工厂/门店，报价与采购跳原单并严格限定供应商');
  await page.setViewportSize({width:375,height:812});
  for (const module of ['customers','suppliers']) {
    await go('#'+module);
    if(module==='suppliers'){await page.locator('[data-partner-kind="distributor"]').click();await idle();}
    const sizes=await page.evaluate(()=>({width:innerWidth,body:document.documentElement.scrollWidth}));
    assert(sizes.body<=sizes.width+1,JSON.stringify(sizes));
    await page.screenshot({path:path.join(output,module+'-mobile.png'),fullPage:true});
  }
  check('375px窄屏概览可读，无整页横向溢出');
  assert.equal((await page.evaluate(()=>api('qa_state'))).digest,before.digest);
  assert.deepEqual(errors,[]);
  check('全部查看/取消未改账本，无浏览器运行错误');
} catch(error) {
  errors.push('Acceptance: '+error.message);
  await page.screenshot({path:path.join(output,'failure.png'),fullPage:false});
  throw error;
} finally {
  await fs.writeFile(path.join(output,'results.json'),JSON.stringify({checks,errors},null,2));
  await browser.close();
}
console.log(JSON.stringify({checks,errors},null,2));
